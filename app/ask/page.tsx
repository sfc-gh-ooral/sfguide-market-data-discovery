'use client';

// Ask the data: the Cortex Agent picks fields from the dictionary (Cortex Search), writes SQL
// with Cortex Analyst over the semantic view, and answers with a chart, the SQL, and citations.
import { BookOpen, ChevronDown, Code2, Send } from 'lucide-react';
import { useSearchParams } from 'next/navigation';
import { Suspense, useEffect, useRef, useState } from 'react';
import { Bars, LineSeries } from '@/components/Charts';
import { DataTable } from '@/components/DataTable';
import { Reasoning } from '@/components/Reasoning';
import { Card, Markdown, PoweredBy, SampleAiBadge, SourceBadge } from '@/components/ui';
import { data } from '@/lib/client';
import { SAMPLE_QUESTIONS } from '@/lib/mock-data';
import type { AskAnswer } from '@/lib/types';

function Answer({ a }: { a: AskAnswer }) {
  const rows = a.table && a.chart ? a.table.rows.map((r) => Object.fromEntries(a.table!.columns.map((c, i) => [c, r[i]]))) : [];
  return (
    <div className="ai-panel space-y-3">
      <div className="flex items-center gap-2 flex-wrap">
        <PoweredBy>Cortex Agent</PoweredBy>
        {a.sample ? <SampleAiBadge /> : <SourceBadge p={a} />}
        {a.tools.map((t) => <span key={t} className="text-[11px] muted">· {t}</span>)}
      </div>
      <Markdown text={a.text} />
      {a.chart && rows.length > 1 && (
        <div className="card p-3">
          {a.chart.kind === 'line'
            ? <LineSeries rows={rows} x={a.chart.x} series={a.chart.series} />
            : <Bars rows={rows} x={a.chart.x} series={a.chart.series} />}
        </div>
      )}
      {a.cites.length > 0 && (
        <div>
          <div className="text-xs font-semibold mb-1 flex items-center gap-1"><BookOpen className="w-3.5 h-3.5" aria-hidden />Dictionary entries used</div>
          <ul className="space-y-1">
            {a.cites.map((c) => <li key={c.field} className="text-xs text-2"><code className="font-semibold">{c.field}</code>: {c.description}</li>)}
          </ul>
        </div>
      )}
      {a.sql && (
        <details className="card p-3">
          <summary className="text-xs font-semibold cursor-pointer flex items-center gap-1"><Code2 className="w-3.5 h-3.5" aria-hidden />SQL{a.sample ? ' (sample)' : ' generated by Cortex Analyst'}<ChevronDown className="w-3 h-3" aria-hidden /></summary>
          <pre className="text-xs mt-2 overflow-x-auto whitespace-pre">{a.sql}</pre>
        </details>
      )}
      {a.table && (
        <details className="card p-3">
          <summary className="text-xs font-semibold cursor-pointer">Result ({a.table.rows.length.toLocaleString()} rows)</summary>
          <div className="mt-2"><DataTable columns={a.table.columns} rows={a.table.rows} max={25} /></div>
        </details>
      )}
    </div>
  );
}

function Ask() {
  const initial = useSearchParams().get('q');
  const [q, setQ] = useState(initial ?? '');
  const [turns, setTurns] = useState<{ q: string; a?: AskAnswer; error?: string }[]>([]);
  const busy = turns.some((t) => !t.a && !t.error);
  const asked = useRef(false);

  const ask = async (question: string) => {
    if (!question.trim() || busy) return;
    setQ('');
    setTurns((t) => [{ q: question }, ...t]);
    try {
      const a = await data.ask(question);
      setTurns((t) => t.map((x) => (x.q === question && !x.a && !x.error ? { ...x, a } : x)));
    } catch (e) {
      setTurns((t) => t.map((x) => (x.q === question && !x.a && !x.error ? { ...x, error: String((e as Error).message ?? e) } : x)));
    }
  };
  useEffect(() => {
    if (initial && !asked.current) { asked.current = true; ask(initial); }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [initial]);

  return (
    <div className="space-y-5">
      <div>
        <h1 className="page-title">Ask the data</h1>
        <p className="text-sm muted">Plain-English questions over the vendor datasets and your client books. The agent checks the data dictionary before it picks a field.</p>
      </div>
      <Card>
        <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); ask(q); }}>
          <label className="sr-only" htmlFor="ask-q">Question</label>
          <input id="ask-q" value={q} onChange={(e) => setQ(e.target.value)} maxLength={500} placeholder="Ask about securities, prices, ESG, or your client books…"
            className="flex-1 min-w-0 rounded-lg px-3 py-2 text-sm" style={{ background: 'var(--surface-2)', border: '1px solid var(--border)' }} />
          <button className="btn btn-primary" disabled={busy || !q.trim()}><Send className="w-4 h-4" aria-hidden />Ask</button>
        </form>
        <div className="flex flex-wrap gap-2 mt-3">
          {SAMPLE_QUESTIONS.map((s) => <button key={s} className="btn btn-ai text-xs" disabled={busy} onClick={() => ask(s)}>{s}</button>)}
        </div>
      </Card>
      {turns.map((t, i) => (
        <Card key={turns.length - i} title={t.q}>
          {t.a ? <Answer a={t.a} /> : t.error ? <p className="text-sm" style={{ color: 'var(--negative)' }}>The agent call failed: {t.error}</p> : <Reasoning />}
        </Card>
      ))}
    </div>
  );
}

export default function AskPage() {
  return <Suspense fallback={<div className="muted text-sm">Loading…</div>}><Ask /></Suspense>;
}
